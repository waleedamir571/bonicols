        </section>

        <!-- What Can a Prenup Cover Section -->
        <section class="about-section">
            <div class="auto-container">
                <div class="sec-title centered">
                    <h2 class="theme-color">What Can a Texas Prenuptial Agreement Cover?</h2>
                </div>
                <div class="paragraph-container">
                    <p class="text text-center">Texas law gives couples significant flexibility when drafting prenuptial agreements, provided the terms are legal and fair. A prenup may address:</p>

                    <h4 class="text-center" style="margin-top: 20px; margin-bottom: 10px; color: #c4a961;"><strong>Separate vs. Community Property</strong></h4>
                    <p class="text text-center">Couples can define which assets remain separate property and which become marital property during the marriage.</p>

                    <h4 class="text-center" style="margin-top: 20px; margin-bottom: 10px; color: #c4a961;"><strong>Business Interests</strong></h4>
                    <p class="text text-center">A prenup can protect ownership rights in privately owned businesses, partnerships, or professional practices.</p>

                    <h4 class="text-center" style="margin-top: 20px; margin-bottom: 10px; color: #c4a961;"><strong>Real Estate</strong></h4>
                    <p class="text text-center">Agreements may clarify ownership rights involving homes, investment properties, vacation properties, or rental income.</p>

                    <h4 class="text-center" style="margin-top: 20px; margin-bottom: 10px; color: #c4a961;"><strong>Debt Protection</strong></h4>
                    <p class="text text-center">Couples can determine responsibility for certain debts acquired before or during the marriage.</p>

                    <h4 class="text-center" style="margin-top: 20px; margin-bottom: 10px; color: #c4a961;"><strong>Spousal Support</strong></h4>
                    <p class="text text-center">Prenuptial agreements may include provisions involving future spousal maintenance or financial support.</p>

                    <h4 class="text-center" style="margin-top: 20px; margin-bottom: 10px; color: #c4a961;"><strong>Estate Planning Considerations</strong></h4>
                    <p class="text text-center">Prenups often work alongside estate plans to protect inheritance goals and family wealth.</p>

                    <p class="text text-center" style="margin-top: 20px;">However, Texas courts generally will not enforce provisions involving child custody or child support decisions in prenuptial agreements because those matters must always serve the child's best interests at the time of the dispute.</p>
                </div>
            </div>
        </section>

        <!-- Enforceability Section -->
        <section class="about-section">
            <div class="auto-container">
                <div class="sec-title centered">
                    <h2 class="theme-color">What Makes a Prenup Enforceable in Texas?</h2>
                </div>
                <div class="paragraph-container">
                    <p class="text text-center">Not every prenuptial agreement automatically holds up in court. To be enforceable under Texas law, several important requirements must be met.</p>

                    <h4 class="text-center" style="margin-top: 20px; margin-bottom: 10px; color: #c4a961;"><strong>The Agreement Must Be Voluntary</strong></h4>
                    <p class="text text-center">Both parties must sign willingly without coercion, threats, or improper pressure.</p>

                    <h4 class="text-center" style="margin-top: 20px; margin-bottom: 10px; color: #c4a961;"><strong>Financial Disclosure Is Critical</strong></h4>
                    <p class="text text-center">Each party should fully disclose assets, liabilities, income, and financial obligations before signing the agreement.</p>

                    <h4 class="text-center" style="margin-top: 20px; margin-bottom: 10px; color: #c4a961;"><strong>The Agreement Must Be Properly Drafted</strong></h4>
                    <p class="text text-center">Poorly written agreements containing vague language or legal errors may become vulnerable to challenges later.</p>

                    <h4 class="text-center" style="margin-top: 20px; margin-bottom: 10px; color: #c4a961;"><strong>Timing Matters</strong></h4>
                    <p class="text text-center">Last-minute prenups signed days before a wedding can create claims of pressure or unfairness. Ideally, couples should begin discussions well before the wedding date.</p>

                    <p class="text text-center" style="margin-top: 20px;">An experienced family law attorney can help ensure the agreement is properly structured to reduce the risk of future disputes or invalidation.</p>
                </div>
            </div>
        </section>

