            <div class="auto-container">
                <div class="sec-title centered">
                    <h2 class="theme-color">What Is a Prenuptial Agreement?</h2>
                </div>
                <div class="paragraph-container">
                    <p class="text text-center">A prenuptial agreement, often called a prenup, is a legally binding contract created before marriage that outlines how certain financial matters will be handled if the marriage ends in divorce or death.</p>

                    <p class="text text-center"><strong>Under Texas law, prenuptial agreements can address issues such as:</strong></p>
                    <ul class="text text-center" style="list-style-position: inside; margin: 15px auto;">
                        <li>Separate property protection</li>
                        <li>Division of marital assets</li>
                        <li>Business ownership interests</li>
                        <li>Debt responsibility</li>
                        <li>Spousal support agreements</li>
                        <li>Real estate ownership</li>
                        <li>Inheritance rights</li>
                        <li>Financial obligations during marriage</li>
                    </ul>

                    <p class="text text-center" style="margin-top: 15px;">Texas follows community property laws, meaning most assets acquired during marriage are generally considered jointly owned. A prenuptial agreement allows couples to establish different arrangements that better fit their specific financial circumstances.</p>
                </div>
            </div>
        </section>

        <!-- Why Prenups Are Common Section -->
        <section class="about-section">
            <div class="auto-container">
                <div class="sec-title centered">
                    <h2 class="theme-color">Why Prenups Are Becoming More Common</h2>
                </div>
                <div class="paragraph-container">
                    <p class="text text-center">Prenuptial agreements have become increasingly popular in recent years, particularly among younger professionals and individuals entering second marriages. Several factors are driving this trend:</p>

