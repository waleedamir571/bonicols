                                    <h3>Can a Spouse Be Ordered to Support a Child After the Child Turns 18?</h3>

                                    <div class="text">
                                        For many parents, a child's 18th birthday feels like an important legal
                                        milestone. But does turning 18 automatically end a parent's child support
                                        obligation in Texas?

                                        <br><br>
                                        Not always.

                                        <br><br>
                                        Texas law generally provides that child support continues until a child turns 18
                                        or graduates from high school, whichever occurs later. However, Texas law also
                                        provides circumstances in which support may continue after a child's 18th
                                        birthday. These exceptions can be particularly important when a child is still
                                        completing high school or has a qualifying mental or physical disability.

                                        <br><br>
                                        If you are approaching the end of a child support order, understanding when
                                        support ends and when it may continue can help you avoid confusion and
                                        unexpected legal problems.
                                    </div>

                                    <h3>When Does Child Support Normally End in Texas?</h3>
                                    <div class="text">
                                        Under Texas Family Code Section 154.001, a court may order child support until
                                        the child reaches 18 years of age or graduates from high school, whichever
                                        occurs later. The law also identifies other events that can end support,
                                        including emancipation through marriage or other operation of law and the
                                        child's death.

                                        <br><br>
                                        This means a parent should not automatically assume that child support stops on
                                        the child's 18th birthday.

                                        <br><br>
                                        For example, if a child turns 18 while still enrolled in high school and
                                        otherwise meets the statutory requirements, child support may continue through
                                        graduation.

                                        <br><br>
                                        The exact language of the existing support order also matters, so parents should
                                        review their order rather than relying solely on a general rule.
                                    </div>

                                    <h3>Can Child Support Continue After 18 If the Child Is Still in High School?</h3>
                                    <div class="text">
                                        Yes.

                                        <br><br>
                                        Texas Family Code Section 154.002 allows a court to order child support beyond a
                                        child's 18th birthday when the child remains enrolled in an eligible
                                        secondary-school program and meets applicable attendance requirements. The
                                        request for an order extending support through high-school graduation may be
                                        filed before or after the child's 18th birthday.

                                        <br><br>
                                        Under the statute, qualifying enrollment can include:
                                        <br><br>
                                        <ul>
                                            <li>An accredited secondary school program leading toward a high school
                                                diploma</li>
                                            <li>Certain programs providing joint high school and junior college credit
                                            </li>
                                            <li>A qualifying full-time private secondary school program leading toward a
                                                high school diploma</li>
                                        </ul>
                                        <br>
                                        The child must also comply with the applicable attendance requirements.

                                        <br><br>
                                        A court order may provide for payments to continue through the end of the month
                                        in which the child graduates.
                                    </div>

                                    <h3>Why Does This Matter?</h3>
                                    <div class="text">
                                        Imagine a child turns 18 in March but is scheduled to graduate from high school
                                        in May.

                                        <br><br>
                                        The parent's support obligation does not necessarily end simply because the
                                        child had an 18th birthday in March. Depending on the circumstances and the
                                        applicable order, support may continue through graduation.

                                        <br><br>
                                        This is one reason it is important to understand the terms of your Texas child
                                        support order before stopping or changing payments.
                                    </div>

                                    <h3>Can a Parent Be Required to Support an Adult Child With a Disability?</h3>
                                    <div class="text">
                                        Yes. This is one of the most significant exceptions to the general rule.

                                        <br><br>
                                        Texas Family Code Section 154.302 allows a court to order either or both parents
                                        to provide support for a child for an indefinite period if specific requirements
                                        are met. The law applies when the child requires substantial care and personal
                                        supervision because of a mental or physical disability and will not be capable
                                        of self-support. The disability, or its cause, must exist or be known to exist
                                        on or before the child's 18th birthday.

                                        <br><br>
                                        This means that, in qualifying circumstances, child support can continue well
                                        beyond age 18.

                                        <br><br>
                                        The court may determine the amount of support and the rights and duties of the
                                        parents based on the circumstances of the adult child.
                                    </div>

                                    <h3>What Factors Can the Court Consider for an Adult Child With a Disability?</h3>
                                    <div class="text">
                                        When determining support for an adult child with a qualifying disability, Texas
                                        law directs the court to give special consideration to several factors.

                                        <br><br>
                                        These can include:
                                        <br><br>
                                        <ul>
                                            <li>The adult child's current or future needs related to the disability</li>
                                            <li>The substantial care and personal supervision required</li>
                                            <li>Whether either parent provides or will provide care or supervision</li>
                                            <li>The financial resources available to both parents</li>
                                            <li>Other financial resources or programs available to support the adult
                                                child</li>
                                        </ul>
                                        <br>
                                        The goal is not simply to extend an ordinary child support order indefinitely.
                                        Instead, the court evaluates the specific needs and circumstances of the adult
                                        child.
                                    </div>

                                    <h3>Does Child Support Automatically Continue After Age 18?</h3>
                                    <div class="text">
                                        Not necessarily.

                                        <br><br>
                                        Whether support continues depends on the circumstances and the applicable court
                                        order.

                                        <br><br>
                                        For a child who remains in high school, the statutory requirements for continued
                                        support must be satisfied. For an adult child with a disability, the
                                        requirements under Texas Family Code Chapter 154 must be met.

                                        <br><br>
                                        Parents should also understand the difference between current child support and
                                        past-due child support, or arrears.

                                        <br><br>
                                        A child's 18th birthday does not simply erase unpaid child support that accrued
                                        under a valid order. Questions concerning arrears, enforcement, and termination
                                        can involve different legal considerations.

                                        <br><br>
                                        If you are unsure whether your support obligation has ended, it is safer to
                                        review the order and obtain legal advice than to simply stop making payments.
                                    </div>

                                    <h3>What If the Child Graduates After Turning 18?</h3>
                                    <div class="text">
                                        This is a common source of confusion.

                                        <br><br>
                                        Texas law specifically allows child support to continue beyond the 18th birthday
                                        when the statutory requirements for support through high-school graduation are
                                        met. The court may provide for payments through the end of the month in which
                                        the child graduates.

                                        <br><br>
                                        However, parents should not assume that every 18-year-old student automatically
                                        qualifies.

                                        <br><br>
                                        The child's enrollment and attendance must meet the requirements established by
                                        Texas law.
                                    </div>

                                    <h3>What If the Child Has a Disability but Is Already 18?</h3>
                                    <div class="text">
                                        A parent seeking support for an adult child with a disability should pay close
                                        attention to the statutory requirements.

                                        <br><br>
                                        Texas law requires, among other things, that the disability exist or that its
                                        cause be known to exist, on or before the child's 18th birthday. The child must
                                        also require substantial care and personal supervision because of the disability
                                        and be unable to support themselves.

                                        <br><br>
                                        Because these cases can involve medical evidence, financial information,
                                        caregiving arrangements, and questions about available benefits or resources,
                                        they can be significantly more complicated than a standard child support case.
                                    </div>

                                    <h3>What Happens to Child Support When One Child Turns 18?</h3>
                                    <div class="text">
                                        Families with multiple children may have another issue to consider.

                                        <br><br>
                                        When support for one child terminates, the total child support obligation may
                                        need to be adjusted for the remaining children. Texas Family Code Section
                                        154.127 addresses partial termination of support and requires the support level
                                        for the remaining children to comply with the applicable guidelines.

                                        <br><br>
                                        This means a parent paying support for multiple children should not assume that
                                        the entire child support obligation ends when the oldest child reaches the
                                        applicable termination event.

                                        <br><br>
                                        The support order may specify how the amount changes when support for one child
                                        ends.
                                    </div>

                                    <h3>Do You Need to Modify a Child Support Order?</h3>
                                    <div class="text">
                                        Every family situation is different.

                                        <br><br>
                                        If your child is approaching 18, graduating from high school, or has a
                                        qualifying disability, it may be important to determine exactly what your
                                        current order requires and whether a modification or other court action is
                                        appropriate.

                                        <br><br>
                                        Issues can become particularly complicated when:
                                        <br><br>
                                        <ul>
                                            <li>The child is still in high school after turning 18</li>
                                            <li>The child has a qualifying mental or physical disability</li>
                                            <li>Multiple children are covered by the same support order</li>
                                            <li>There are significant child support arrears</li>
                                            <li>The parents disagree about whether support should continue</li>
                                            <li>The existing order does not clearly address termination</li>
                                        </ul>
                                        <br>
                                        Getting advice before a support obligation changes can help prevent unnecessary
                                        disputes and enforcement problems.
                                    </div>

                                    <h3>Understanding Child Support After 18 in Texas</h3>
                                    <div class="text">
                                        So, can a spouse be ordered to support a child after the child turns 18?

                                        <br><br>
                                        Yes, in certain circumstances.

                                        <br><br>
                                        The general rule in Texas is that child support continues until the child turns
                                        18 or graduates from high school, whichever occurs later. But Texas law also
                                        permits support to continue through high school graduation when statutory
                                        requirements are met and allows courts to order support for an adult child with
                                        a qualifying disability for an indefinite period.

                                        <br><br>
                                        Because the specific facts of your family and the language of your court order
                                        matter, do not assume that support automatically stops or automatically
                                        continues, when a child turns 18.

