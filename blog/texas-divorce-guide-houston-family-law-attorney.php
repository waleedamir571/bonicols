                                            <li>Retirement accounts</li>
                                            <li>Business interests</li>
                                            <li>Investments</li>
                                            <li>Debt allocation</li>
                                            <li>Hidden assets</li>
                                            <li>Separate property claims</li>
                                            <li>Executive compensation or bonuses</li>
                                        </ul>
