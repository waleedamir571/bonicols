                                        <div class="text">Moving out of state with a child is very different from simply
                                            changing your own residence. Your custody order may contain restrictions
                                            that affect where your child can live, and an interstate move can
                                            significantly affect the other parent's possession and access.</div>
                                        <div class="text">Before relocating, review your custody order and understand
